"""Build the hosted no-account example in docs/try/ (run: npm run build:example).

Needs the app's Python packages (pip install -r app/requirements.txt). Runs the
app's own data layer (app/data.py) in Sample mode over the bundled CSVs, so every
number in docs/try/ is the number the Streamlit app shows, and bundles the
captured Sample AI responses. Copies the fonts the guide and example share, and
writes docs/.nojekyll so GitHub Pages serves every file as-is.
"""
import json
import os
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
sys.path.insert(0, str(ROOT / "app"))
os.environ.setdefault("STREAMLIT_GLOBAL_DEVELOPMENT_MODE", "false")
import data  # noqa: E402


def r(x, d=2):
    return None if pd.isna(x) else round(float(x), d)


h = data.health("Sample")
d = data.demand("Sample")
m = data.monthly(h)
cs = data.category_summary(h, d)
sl = data.save_list(h)
first_churn = h[h.churned_flag].groupby("merchant_id").month.min()
months = [f"{x:%Y-%m-%d}" for x in m.month]

out = {
    "months": months,
    "monthly": {k: [int(v) for v in m[k]] for k in ["healthy", "watch", "at-risk", "churned", "active"]}
               | {"nrr": [r(v) for v in m.nrr], "volume": [int(v) for v in m.volume]},
    "first_churn": sorted(f"{v:%Y-%m-%d}" for v in first_churn),
    "categories": [{
        "code": c.category_code, "name": c.category, "diagnosis": c.diagnosis, "book_yoy": r(c.book_yoy),
        "demand_yoy": r(c.demand_yoy), "gap": r(c.gap), "nrr": r(c.nrr), "churn_rate": r(c.churn_rate),
        "active": c.active, "healthy": c.healthy, "watch": c.watch, "at_risk": c.at_risk, "churned": c.churned,
        "trend": c.trend,
    } for c in cs.itertuples()],
    "cat_series": {},
    "merchants": [],
}
for code, g in h.groupby("category_code"):
    v = g.groupby("month").monthly_volume_usd.sum()
    b = g.groupby("month").baseline_monthly_volume.sum()
    dd = d[d.category_code == code].set_index("month")
    L = g[g.month == g.month.max()]
    out["cat_series"][code] = {
        "volume": [int(x) for x in v], "nrr": [r(x) for x in v / b * 100],
        "book_yoy": [r(x) for x in (v / v.shift(12) - 1) * 100],
        "demand": [int(dd.loc[x, "market_sales_usd"]) for x in v.index],
        "demand_yoy": [r(dd.loc[x, "yoy_growth_pct"]) for x in v.index],
        "tenure": {t: {bnd: int(((L.tenure_band == t) & (L.risk_band == bnd)).sum()) for bnd in data.BANDS} for t in data.TENURES},
    }
series = h.groupby("merchant_id").vol_ratio.apply(lambda s: [round(x * 100, 1) for x in s])
for x in sl.itertuples():
    out["merchants"].append({
        "id": x.merchant_id, "cat": x.category_code, "cat_name": x.category_name, "band": x.risk_band,
        "vol": int(x.monthly_volume_usd), "base": int(x.baseline_monthly_volume), "ratio": r(x.vol_ratio, 4),
        "chg3": r(x.vol_3m_change, 1), "idle": int(x.days_since_last_txn), "tickets": int(x.support_tickets),
        "declining": int(x.months_declining), "tenure": x.tenure_band,
        "churned_since": None if pd.isna(x.churned_since) else f"{x.churned_since:%Y-%m-%d}",
        "series": series[x.merchant_id],
    })
out["ai"] = json.loads((ROOT / "app" / "sample" / "ai.json").read_text())

(DOCS / "try").mkdir(parents=True, exist_ok=True)
(DOCS / "try" / "data.js").write_text("/* Generated by scripts/build_example.py from app/sample/ via app/data.py. */\nwindow.MAEW = "
                                     + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
fonts = DOCS / "fonts"
fonts.mkdir(exist_ok=True)
for f in (ROOT / "app" / "static" / "fonts").iterdir():
    shutil.copy(f, fonts / f.name)
(DOCS / ".nojekyll").write_text("")
print("docs/try/data.js written;", len(out["merchants"]), "merchants,", len(out["ai"]["notes"]), "notes,",
      len(out["ai"]["ask"]), "answers")
